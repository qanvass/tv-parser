"""Regenerates lib/repository/provider/running_series_data.dart.

The list of series that began before 2020 and are still running (an episode
aired in roughly the last 18 months), each with the number of its first
season from 2020 or later. TV Parser keeps those shows, hides their older
seasons, and drops every other series from before 2020 (see
catalog_age_policy.dart, Quasar 2026-11-26).

Run from azul_iptv:  python tool/gen_running_series.py
Needs ../.secrets/tmdb.json ({"api_key": ...}). The key is never written out.
Run it again before each release build: shows end and new ones are revived.
"""
import concurrent.futures as cf
import datetime
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
KEY = json.load(open(os.path.join(APP, '..', '.secrets', 'tmdb.json')))['api_key']
OUT = os.path.join(APP, 'lib', 'repository', 'provider', 'running_series_data.dart')
CUTOFF_YEAR = 2020
TODAY = datetime.date.today()
AIRED_SINCE = (TODAY - datetime.timedelta(days=548)).isoformat()


def get(path, **params):
    params['api_key'] = KEY
    url = 'https://api.themoviedb.org/3' + path + '?' + urllib.parse.urlencode(params)
    for attempt in range(6):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:
                return json.load(r)
        except Exception as e:  # rate limit or a network blip
            code = getattr(e, 'code', None)
            if code == 404:
                return None
            time.sleep(1.5 * (attempt + 1))
    raise SystemExit('TMDB did not answer for ' + path)


def squash(title):
    """Must match CatalogAgePolicy.titleKey in Dart."""
    t = (title or '').lower().replace('&', ' and ')
    return re.sub(r'[^a-z0-9]+', '', t)


def discover_page(page):
    return get('/discover/tv', **{
        'first_air_date.lte': '%d-12-31' % (CUTOFF_YEAR - 1),
        'air_date.gte': AIRED_SINCE,
        'sort_by': 'popularity.desc',
        'page': page,
    })


first = discover_page(1)
pages = min(first['total_pages'], 500)
shows = {s['id']: s for s in first['results']}
with cf.ThreadPoolExecutor(8) as pool:
    for r in pool.map(discover_page, range(2, pages + 1)):
        for s in (r or {}).get('results', []):
            shows[s['id']] = s
print('still-running shows from before %d: %d' % (CUTOFF_YEAR, len(shows)), file=sys.stderr)


def detail(show_id):
    return get('/tv/%d' % show_id)


entries = {}
kept = 0
with cf.ThreadPoolExecutor(8) as pool:
    for d in pool.map(detail, list(shows)):
        if not d:
            continue
        first_year = int((d.get('first_air_date') or '0000')[:4] or 0)
        if not first_year or first_year >= CUTOFF_YEAR:
            continue
        numbered = [s for s in d.get('seasons', []) if (s.get('season_number') or 0) >= 1]
        recent = [s['season_number'] for s in numbered
                  if (s.get('air_date') or '')[:4].isdigit() and int(s['air_date'][:4]) >= CUTOFF_YEAR]
        if recent:
            min_season = min(recent)
        elif numbered:
            # One long season that began before 2020 and is still on (soaps, talk shows).
            min_season = max(s['season_number'] for s in numbered)
        else:
            min_season = 1
        for name in {d.get('name'), d.get('original_name')}:
            key = squash(name)
            if len(key) < 2:
                continue
            pair = (first_year, min_season)
            if pair not in entries.setdefault(key, []):
                entries[key].append(pair)
        kept += 1

lines = [
    '// GENERATED by tool/gen_running_series.py on %s. Do not edit by hand.' % TODAY.isoformat(),
    '//',
    '// Series that began before %d and aired an episode since %s (TMDB).' % (CUTOFF_YEAR, AIRED_SINCE),
    '// Key: title squashed to a-z0-9 (CatalogAgePolicy.titleKey).',
    '// Value: pairs of [first year, first season from %d or later].' % CUTOFF_YEAR,
    '// %d shows, %d title keys.' % (kept, len(entries)),
    '// ignore_for_file: lines_longer_than_80_chars',
    "const String runningSeriesGeneratedOn = '%s';" % TODAY.isoformat(),
    'const Map<String, List<int>> runningSeriesBefore2020 = <String, List<int>>{',
]
for key in sorted(entries):
    flat = ', '.join('%d, %d' % p for p in sorted(entries[key]))
    lines.append("  '%s': <int>[%s]," % (key, flat))
lines.append('};')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote %s: %d shows, %d keys' % (os.path.relpath(OUT, APP), kept, len(entries)), file=sys.stderr)
